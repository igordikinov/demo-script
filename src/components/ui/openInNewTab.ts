// Открытие адреса в новой вкладке — «Открыть экран» (SPEC §4.9:354) и
// «Открыть в новой вкладке» у карты процесса (§4.6:316). Одна реализация на
// оба места, чтобы правила открытия не разошлись.
//
// Без 'noopener' (решение DN-cx3): с ним window.open всегда возвращает null, и
// блокировку (iframe вики с sandbox) было бы не отличить от обычного открытия.
// Поэтому opener у открытой вкладки обнуляется вручную. Что показать при
// блокировке, решает вызывающий: этот модуль тост не знает.

/**
 * Открывает `url` в новой вкладке, у вкладки `opener = null`.
 * false — браузер не дал открыть вкладку (`window.open` вернул null).
 */
export function openInNewTab(url: string): boolean {
  const tab = window.open(url, '_blank');
  if (tab === null) {
    return false;
  }
  tab.opener = null;
  return true;
}
